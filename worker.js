function redirect(location, cookie) {
  const headers = securityHeaders({
    Location: location,
    "Cache-Control": "no-store, max-age=0",
  });
  if (cookie) headers.append("Set-Cookie", cookie);
  return new Response(null, { status: 303, headers });
}

function clearSessionCookie() {
  return `${SESSION_COOKIE}=; Max-Age=0; Path=/; HttpOnly; Secure; SameSite=Strict`;
}

function addAssetHeaders(response) {
  const headers = securityHeaders(response.headers);
  const contentType = headers.get("Content-Type") || "";

  // Keep HTML fresh while allowing private browser caching for large models,
  // images, and audio during long mobile/desktop test sessions.
  if (contentType.includes("text/html")) {
    headers.set("Cache-Control", "private, no-store, max-age=0");
  } else {
    headers.set("Cache-Control", "private, max-age=3600, must-revalidate");
  }
  headers.set("Vary", "Cookie");

  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const signingSecret = env.SESSION_SECRET;

    // Fail closed: no game file can be served until both secrets exist.
    if (!env.LAB_PIN || !signingSecret) {
      return htmlResponse(
        loginPage("Alpha access is not configured yet."),
        503
      );
    }

    if (url.pathname === LOGIN_PATH) {
      if (request.method !== "POST") return redirect("/");

      if (!isTrustedLoginRequest(request, url)) {
        return htmlResponse(loginPage("That request was not accepted."), 403);
      }

      const key = clientKey(request);
      if (isRateLimited(key)) {
        return htmlResponse(
          loginPage("Too many attempts. Wait 15 minutes and try again."),
          429,
          { "Retry-After": "900" }
        );
      }

      let supplied = "";
      try {
        const form = await request.formData();
        supplied = String(form.get("pin") || "").trim();
      } catch {
        recordFailure(key);
        return htmlResponse(
          loginPage("That request could not be read. Try again."),
          400
        );
      }

      if (!(await pinMatches(supplied, String(env.LAB_PIN), signingSecret))) {
        recordFailure(key);
        return htmlResponse(loginPage("That PIN was not accepted."), 401);
      }

      clearFailures(key);
      const token = await createSession(signingSecret);
      const cookie = [
        `${SESSION_COOKIE}=${token}`,
        `Max-Age=${SESSION_TTL_SECONDS}`,
        "Path=/",
        "HttpOnly",
        "Secure",
        "SameSite=Strict",
      ].join("; ");
      return redirect("/", cookie);
    }

    if (url.pathname === LOGOUT_PATH) {
      return redirect("/", clearSessionCookie());
    }

    if (!(await hasValidSession(request, signingSecret))) {
      return htmlResponse(loginPage());
    }

    if (!env.ASSETS || typeof env.ASSETS.fetch !== "function") {
      return htmlResponse("Alpha asset binding is not configured.", 503);
    }

    const assetResponse = await env.ASSETS.fetch(request);
    return addAssetHeaders(assetResponse);
  },
};

