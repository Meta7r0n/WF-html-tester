// Deployment checkpoint: CFP v0.39.05 / 2026-08-16.
/*
 * Lobster Labz Alpha Lab server-side access gate.
 *
 * Required Cloudflare Worker secrets (never commit their values):
 *   LAB_PIN         shared tester PIN
 *   SESSION_SECRET  long random session-signing secret
 *
 * Every request reaches this Worker before Cloudflare's static asset binding.
 * Anonymous visitors receive only the login page; authenticated visitors can
 * load the game and its assets from public/.
 */

const SESSION_COOKIE = "llz_alpha_session";
const SESSION_TTL_SECONDS = 24 * 60 * 60;
const LOGIN_PATH = "/__alpha/login";
const LOGOUT_PATH = "/__alpha/logout";
const RATE_WINDOW_MS = 15 * 60 * 1000;
const RATE_LIMIT = 8;
const MAX_RATE_KEYS = 500;

// Best-effort edge-local throttle. For a larger public test, add a Cloudflare
// WAF rate-limit rule to the login endpoint as an additional layer.
const failedAttempts = new Map();
const encoder = new TextEncoder();

function base64Url(bytes) {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary)
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/g, "");
}

async function hmac(secret, value) {
  const key = await crypto.subtle.importKey(
    "raw",
    encoder.encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"]
  );
  const signature = await crypto.subtle.sign(
    "HMAC",
    key,
    encoder.encode(value)
  );
  return base64Url(new Uint8Array(signature));
}

function safeEqual(left, right) {
  if (
    typeof left !== "string" ||
    typeof right !== "string" ||
    left.length !== right.length
  ) {
    return false;
  }

  let difference = 0;
  for (let index = 0; index < left.length; index += 1) {
    difference |= left.charCodeAt(index) ^ right.charCodeAt(index);
  }
  return difference === 0;
}

async function pinMatches(supplied, expected, signingSecret) {
  const [suppliedDigest, expectedDigest] = await Promise.all([
    hmac(signingSecret, `pin:${supplied}`),
    hmac(signingSecret, `pin:${expected}`),
  ]);
  return safeEqual(suppliedDigest, expectedDigest);
}

function parseCookies(request) {
  const cookies = {};
  const header = request.headers.get("Cookie") || "";

  for (const part of header.split(";")) {
    const separator = part.indexOf("=");
    if (separator < 0) continue;
    const name = part.slice(0, separator).trim();
    const value = part.slice(separator + 1).trim();
    if (name) cookies[name] = value;
  }

  return cookies;
}

async function createSession(signingSecret) {
  const expires = Math.floor(Date.now() / 1000) + SESSION_TTL_SECONDS;
  const nonceBytes = crypto.getRandomValues(new Uint8Array(16));
  const payload = `v1.${expires}.${base64Url(nonceBytes)}`;
  return `${payload}.${await hmac(signingSecret, payload)}`;
}

async function hasValidSession(request, signingSecret) {
  if (!signingSecret) return false;

  const token = parseCookies(request)[SESSION_COOKIE] || "";
  const parts = token.split(".");
  if (parts.length !== 4 || parts[0] !== "v1") return false;

  const expires = Number(parts[1]);
  if (
    !Number.isSafeInteger(expires) ||
    expires <= Math.floor(Date.now() / 1000)
  ) {
    return false;
  }

  const payload = parts.slice(0, 3).join(".");
  const expected = await hmac(signingSecret, payload);
  return safeEqual(parts[3], expected);
}

function clientKey(request) {
  return request.headers.get("CF-Connecting-IP") || "unknown";
}

function isTrustedLoginRequest(request, url) {
  const fetchSite = (request.headers.get("Sec-Fetch-Site") || "").toLowerCase();

  // Fetch Metadata is generated by modern browsers and is more reliable than
  // comparing Origin to request.url when Cloudflare fronts a custom domain.
  if (fetchSite === "cross-site") return false;
  if (fetchSite === "same-origin") return true;

  const origin = request.headers.get("Origin");
  if (!origin || origin === "null") return true;

  const host = request.headers.get("Host");
  const publicOrigin = host ? `${url.protocol}//${host}` : url.origin;
  return origin === url.origin || origin === publicOrigin;
}

function pruneAttempts(now) {
  for (const [key, attempt] of failedAttempts) {
    if (now - attempt.startedAt >= RATE_WINDOW_MS) failedAttempts.delete(key);
  }

  while (failedAttempts.size > MAX_RATE_KEYS) {
    failedAttempts.delete(failedAttempts.keys().next().value);
  }
}

function isRateLimited(key) {
  const now = Date.now();
  pruneAttempts(now);
  const current = failedAttempts.get(key);

  if (!current || now - current.startedAt >= RATE_WINDOW_MS) {
    failedAttempts.set(key, { startedAt: now, count: 0 });
    return false;
  }

  return current.count >= RATE_LIMIT;
}

function recordFailure(key) {
  const now = Date.now();
  const current = failedAttempts.get(key);

  if (!current || now - current.startedAt >= RATE_WINDOW_MS) {
    failedAttempts.set(key, { startedAt: now, count: 1 });
    return;
  }

  current.count += 1;
}

function clearFailures(key) {
  failedAttempts.delete(key);
}

function securityHeaders(initialHeaders = {}) {
  const headers = new Headers(initialHeaders);
  headers.set("X-Content-Type-Options", "nosniff");
  headers.set("X-Frame-Options", "DENY");
  headers.set("Referrer-Policy", "no-referrer");
  // Voice chat remains available; unrelated sensitive browser APIs are denied.
  headers.set("Permissions-Policy", "camera=(), geolocation=(), payment=(), usb=()");
  headers.set("X-Robots-Tag", "noindex, nofollow, noarchive");
  return headers;
}

function htmlResponse(body, status = 200, extraHeaders = {}) {
  const headers = securityHeaders(extraHeaders);
  headers.set("Content-Type", "text/html; charset=UTF-8");
  headers.set("Cache-Control", "no-store, max-age=0");
  headers.set(
    "Content-Security-Policy",
    "default-src 'none'; style-src 'unsafe-inline'; form-action 'self'; base-uri 'none'; frame-ancestors 'none'"
  );
  return new Response(body, { status, headers });
}

