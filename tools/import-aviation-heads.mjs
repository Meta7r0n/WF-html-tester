#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const EXPECTED_COUNT = 123;
const CONTRACT = '0x0322f6f11a94cfb1b5b6e95e059d8deb2bf17d6a';
const COLLECTION_URL = 'https://opensea.io/collection/badbad';
const TRAIT_FILTER = [{ traitType: 'head', values: ['aviation_hat'] }];
const OUTPUT_DIR = path.resolve('assets/aviation-heads');

function argValue(name) {
  const prefix = `--${name}=`;
  const found = process.argv.find(value => value.startsWith(prefix));
  return found ? found.slice(prefix.length) : null;
}

function collectionPageUrl(page) {
  const query = new URLSearchParams({
    page: String(page),
    traits: JSON.stringify(TRAIT_FILTER)
  });
  return `${COLLECTION_URL}?${query}`;
}

async function loadPages() {
  const htmlDir = argValue('html-dir');
  if (htmlDir) {
    const names = ['opensea-badbad.html', 'opensea-badbad-p2.html', 'opensea-badbad-p3.html'];
    return Promise.all(names.map(name => readFile(path.join(htmlDir, name), 'utf8')));
  }

  const pages = [];
  for (let page = 1; page <= 3; page += 1) {
    const response = await fetch(collectionPageUrl(page), {
      headers: { 'user-agent': 'Mozilla/5.0 WiltedFarms-Aviation-Pack/1.0' }
    });
    if (!response.ok) throw new Error(`OpenSea page ${page} returned ${response.status}`);
    pages.push(await response.text());
  }
  return pages;
}

function normalizeAttributes(attributes) {
  const normalized = {};
  for (const entry of attributes) normalized[entry.traitType] = entry.value;
  return normalized;
}

function parseItems(html) {
  const items = [];
  // Collection payloads contain their own logo image before each item's
  // media. Anchor on isTransferLocked so imageUrl is the token artwork,
  // never the repeated collection logo nested earlier in the same object.
  const itemPattern = /"tokenId":"(\d+)"[\s\S]{0,12000}?"isTransferLocked":(?:true|false),"imageUrl":"([^"]+)"[\s\S]{0,5000}?"attributes":(\[[^\]]*\])/g;
  let match;
  while ((match = itemPattern.exec(html))) {
    const attributes = JSON.parse(match[3]);
    const traits = normalizeAttributes(attributes);
    if (traits.head !== 'aviation_hat') continue;
    const tokenId = Number(match[1]);
    items.push({
      id: `aviation-${tokenId}`,
      tokenId,
      name: `Cryptoon Goon #${tokenId}`,
      sourceUrl: `https://opensea.io/item/ethereum/${CONTRACT}/${tokenId}`,
      imageUrl: match[2].replace(/\?.*$/, ''),
      traits,
      designSeed: tokenId
    });
  }
  return items;
}

function javascriptManifest(items) {
  const payload = JSON.stringify(items, null, 2);
  return `/* Generated by tools/import-aviation-heads.mjs. Do not hand-edit. */\n` +
    `(function (root) {\n` +
    `  'use strict';\n` +
    `  root.AVIATION_HEAD_MANIFEST = Object.freeze(${payload});\n` +
    `})(typeof window !== 'undefined' ? window : globalThis);\n`;
}

async function downloadReferences(items, directory) {
  const destination = path.resolve(directory);
  await mkdir(destination, { recursive: true });
  const queue = items.slice();
  const workers = Array.from({ length: 8 }, async () => {
    while (queue.length) {
      const item = queue.shift();
      const response = await fetch(`${item.imageUrl}?w=320`, {
        headers: { 'user-agent': 'Mozilla/5.0 WiltedFarms-Aviation-Pack/1.0' }
      });
      if (!response.ok) throw new Error(`Reference ${item.tokenId} returned ${response.status}`);
      const bytes = new Uint8Array(await response.arrayBuffer());
      await writeFile(path.join(destination, `${item.tokenId}.png`), bytes);
    }
  });
  await Promise.all(workers);
}

const pages = await loadPages();
const unique = new Map();
for (const page of pages) {
  for (const item of parseItems(page)) unique.set(item.tokenId, item);
}
const items = [...unique.values()].sort((a, b) => a.tokenId - b.tokenId);

if (items.length !== EXPECTED_COUNT) {
  throw new Error(`Expected ${EXPECTED_COUNT} aviation_hat characters, found ${items.length}`);
}
if (items.some(item => item.traits.head !== 'aviation_hat')) {
  throw new Error('Manifest contains a character outside the aviation_hat proposal');
}

await mkdir(OUTPUT_DIR, { recursive: true });
await writeFile(path.join(OUTPUT_DIR, 'manifest.json'), `${JSON.stringify({
  schemaVersion: 1,
  collection: 'badbad (formerly Cryptoon Goonz)',
  contract: CONTRACT,
  source: collectionPageUrl(1),
  trait: { head: 'aviation_hat' },
  count: items.length,
  generatedAt: new Date().toISOString(),
  items
}, null, 2)}\n`);
await writeFile(path.join(OUTPUT_DIR, 'manifest.js'), javascriptManifest(items));

const referenceDir = argValue('download-references');
if (referenceDir) await downloadReferences(items, referenceDir);

console.log(`Wrote ${items.length} aviation heads to ${OUTPUT_DIR}`);
